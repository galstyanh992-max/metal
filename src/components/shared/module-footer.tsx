export function ModuleFooter({
  title,
  whatIsIt,
  howToUse,
  tips,
}: {
  title: string;
  whatIsIt: string;
  howToUse: string[];
  tips?: string[];
}) {
  return (
    <div className="mt-6 border border-hairline bg-muted/20 p-4">
      <div className="flex items-start gap-3">
        <Info className="size-5 text-primary shrink-0 mt-0.5" />
        <div className="flex-1 min-w-0 space-y-3">
          <div>
            <h3 className="text-sm font-semibold text-foreground mb-1">
              Ի՞նչ է «{title}» բաժինը
            </h3>
            <p className="text-xs text-muted-foreground leading-relaxed">{whatIsIt}</p>
          </div>

          <div>
            <h4 className="text-xs font-semibold uppercase tracking-wider text-foreground mb-1.5">
              Ինչպես օգտագործել
            </h4>
            <ul className="space-y-1">
              {howToUse.map((step, idx) => (
                <li key={idx} className="text-xs text-muted-foreground flex items-start gap-2">
                  <span className="text-primary font-semibold shrink-0">{idx + 1}.</span>
                  <span className="flex-1">{step}</span>
                </li>
              ))}
            </ul>
          </div>

          {tips && tips.length > 0 && (
            <div>
              <h4 className="text-xs font-semibold uppercase tracking-wider text-status-yellow mb-1.5">
                💡 Խորհուրդներ
              </h4>
              <ul className="space-y-1">
                {tips.map((tip, idx) => (
                  <li key={idx} className="text-xs text-muted-foreground flex items-start gap-2">
                    <span className="text-status-yellow shrink-0">→</span>
                    <span className="flex-1">{tip}</span>
                  </li>
                ))}
              </ul>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}

